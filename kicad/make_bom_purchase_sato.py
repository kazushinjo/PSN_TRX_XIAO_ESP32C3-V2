# 回路図に載っていない部品のうち、サトー電気で買うもの: 品名の先頭一致 → 購入情報
SATO_EXTRA = [
    ('IC ソケット', sato('IC ソケット 8P 一般品（板バネ）', '1個', '20（10個 110）')),
]

def sato_info(row):
    first = row['first']
    if first.startswith('R') and first != 'R27':
        return ('カーボン抵抗 1/4W', carbon(row['value']))
    return SATO_PARTS.get(first)


def extra_sato(name):
    for key, info in SATO_EXTRA:
        if name.startswith(key):
            return info
    return extra_info(name)


def main():
    rows = load_bom()
    extras = md_extra_rows()
    path = os.path.join(HERE, 'bom_purchase_sato.csv')
    n_sato = 0
    with open(path, 'w', encoding='utf-8-sig', newline='') as fh:
        w = csv.writer(fh, lineterminator='\r\n')
        w.writerow(['区分', 'Reference', '品名', '値/型番', 'フットプリント', '数量', '購入先', '購入先の型番',
                    '販売コード', '入数', f'価格（税込、サトー電気 {SATO_CHECKED}／秋月 {CHECKED}）', '購入メモ'])
        for r in rows:
            name, buy = sato_info(r) or (r['name'], r['buy'])
            n_sato += buy[0] == SATO
            w.writerow([r['section'], r['refs'], name, r['value'], r['fp'], r['qty'], *buy])
        for name, qty, _note in extras:
            buy = extra_sato(name)
            n_sato += buy[0] == SATO
            w.writerow(['回路図に載っていない部品', '', name, '', '', qty, *buy])
    print(f'{os.path.basename(path)}: {len(rows)} 行＋回路図外 {len(extras)} 行（うちサトー電気 {n_sato} 行）')


if __name__ == '__main__':
    main()
