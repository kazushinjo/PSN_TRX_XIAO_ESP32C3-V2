import os, sys
import docx
from docx.shared import Mm, Pt
from docx.oxml.ns import qn

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
DOCS = os.path.join(ROOT, 'docs')
DATE = '2026-11-05'
VER = 'V2 Ver 1.1'
TSTYLE = 'Light Grid Accent 1'


class Doc:
    def __init__(self, name):
        self.path = os.path.join(DOCS, name)
        self.d = docx.Document(self.path)
        body = self.d.element.body
        for el in list(body):
            if el.tag != qn('w:sectPr'):
                body.remove(el)
        for rid, rel in list(self.d.part.rels.items()):      # 前の図を消す
            if rel.reltype.endswith('/image'):
                del self.d.part.rels[rid]

    def title(self, t):
        self.d.add_paragraph(t, style='Title')

    def p(self, t='', size=None, bold=None, style='Normal'):
        para = self.d.add_paragraph(style=style)
        if t:
            r = para.add_run(t)
            if size: r.font.size = Pt(size)
            if bold is not None: r.bold = bold
        return para

    def h(self, t, lv=1):
        self.d.add_heading(t, level=lv)

    def b(self, *ts):
        for t in ts:
            self.d.add_paragraph(t, style='List Bullet')

    def n(self, *ts):
        for i, t in enumerate(ts, 1):
            self.d.add_paragraph(f'({i}) {t}')

    def pre(self, *lines):
        for ln in lines:
            para = self.d.add_paragraph()
            para.paragraph_format.space_after = Pt(0)
            r = para.add_run(ln)
            r.font.size = Pt(9)

    def t(self, head, rows):
        tb = self.d.add_table(rows=1, cols=len(head))
        tb.style = self.d.styles[TSTYLE]
        for c, x in zip(tb.rows[0].cells, head):
            c.text = x
        for row in rows:
            cs = tb.add_row().cells
            for c, x in zip(cs, row):
                c.text = x
        for row in tb.rows:
            for c in row.cells:
                for para in c.paragraphs:
                    for r in para.runs:
                        r.font.size = Pt(9)
        self.d.add_paragraph()

    def img(self, path, w=160):
        self.d.add_picture(path, width=Mm(w))

    def save(self):
        self.d.save(self.path)
        print('saved', os.path.relpath(self.path, ROOT))


